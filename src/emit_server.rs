//! `hnl-openapi-server` emitter: OpenAPI document → handl route-map
//! skeleton (`lib-route`/`http-router` shape).
//!
//! One artifact `<server_module>.hnl` (default `openapi_server.hnl`)
//! exporting `routes` — a record the `route.route_map/1` flattener
//! accepts. Each operation becomes a leaf spec record:
//!
//! ```hnl
//! export routes := {
//!   "get_user": {
//!     "handler": (ctx) ~> { "status": 501, "body": "not implemented: get_user" },
//!     "method": "get",
//!     "path": "/users/{id}",
//!     "name": "get_user",
//!     "doc": { "summary": "…", "params": […], "responses": {…} }
//!   },
//!   …
//! }
//! ```
//!
//! Leaf records carry an explicit `path`/`method`/`name`/`doc` — the
//! explicit `path` overrides the key-path derivation, so operations
//! sharing a path template (or differing only by method) never collide
//! in the record map, and per-operation `doc` survives verbatim into
//! the flattened entries (which is what `lib-http-openapi` reads back
//! — this emitter is the spec→routes inverse of the `spec` direction).
//!
//! OpenAPI `{param}` path templates are rewritten to lib-route's
//! `:param` segment-variable spelling.

use handl_plugin_codegen::{Change, CodegenError, EmitContext, Emitter, SpecModule};
use serde_json::Value;
use std::fmt::Write as _;

use crate::config::OpenApiConfig;
use crate::routes::{hnl_string, value_to_hnl};
use crate::spec::{self, Operation};

/// Emitter rendering an OpenAPI [`SpecModule`] to a `.hnl` route map.
pub struct OpenApiServerEmitter;

impl OpenApiServerEmitter {
    pub fn new() -> Self {
        Self
    }
}

impl Default for OpenApiServerEmitter {
    fn default() -> Self {
        Self::new()
    }
}

/// Rewrite an OpenAPI path template to lib-route pattern spelling:
/// `{name}` → `:name`. Embedded params (`/files/{name}.json`) become
/// `:name` prefix-vars, which lib-route's segment compiler accepts.
fn route_pattern(path: &str) -> String {
    let mut out = String::with_capacity(path.len());
    let mut rest = path;
    while let Some(start) = rest.find('{') {
        out.push_str(&rest[..start]);
        let after = &rest[start + 1..];
        match after.find('}') {
            Some(end) => {
                out.push(':');
                out.push_str(&after[..end]);
                rest = &after[end + 1..];
            }
            None => {
                out.push('{');
                rest = after;
            }
        }
    }
    out.push_str(rest);
    out
}

/// The stub handler body for one operation.
fn stub_handler(ident: &str) -> String {
    format!(
        "(ctx) ~> {{ \"status\": 501, \"body\": {} }}",
        hnl_string(&format!("not implemented: {ident}"))
    )
}

/// One leaf record's fields, in stable order.
fn leaf_fields(op: &Operation<'_>, ident: &str) -> String {
    let mut fields = vec![
        format!("\"handler\": {}", stub_handler(ident)),
        format!("\"method\": {}", hnl_string(op.method)),
        format!("\"path\": {}", hnl_string(&route_pattern(op.path))),
        format!("\"name\": {}", hnl_string(ident)),
    ];
    if let Some(doc) = spec::operation_doc(op) {
        fields.push(format!("\"doc\": {}", value_to_hnl(&doc)));
    }
    format!("{{ {} }}", fields.join(", "))
}

impl Emitter<SpecModule> for OpenApiServerEmitter {
    fn materialize(
        &self,
        module: &SpecModule,
        req: &EmitContext,
    ) -> Result<Vec<Change>, CodegenError> {
        let config = OpenApiConfig::for_request(req.config.get("config").map(std::path::Path::new))
            .map_err(CodegenError::Emit)?;
        let ops = spec::operations(module);
        if ops.is_empty() {
            return Err(CodegenError::Emit(
                "openapi spec contains no operations — nothing to emit".to_string(),
            ));
        }
        let raw_names: Vec<String> = ops.iter().map(spec::operation_name).collect();
        let idents = spec::unique_names(&raw_names);

        let module_name = config
            .server_module
            .clone()
            .unwrap_or_else(|| "openapi_server".to_string());
        let title = module
            .document
            .get("info")
            .and_then(|i| i.get("title"))
            .and_then(Value::as_str)
            .unwrap_or("OpenAPI server");

        let mut out = String::new();
        let _ = writeln!(
            out,
            "--- {title} — generated by handl-plugin-codegen-backend-openapi; do not edit\n\
             ---\n\
             --- Route-map skeleton: feed `routes` to route.route_map/1\n\
             --- (opts: methods = the standard verbs) inside http-router.\n\
             --- Handlers are 501 stubs — replace each `handler` arrow.\n\n\
             export routes := {{"
        );
        for (op, ident) in ops.iter().zip(idents.iter()) {
            let _ = write!(
                out,
                "\n  {}: {},",
                hnl_string(ident),
                leaf_fields(op, ident),
            );
        }
        out.push_str("\n}\n");

        Ok(vec![Change::text(format!("{module_name}.hnl"), out)])
    }
}
